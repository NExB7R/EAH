#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════
// EAH — Context Map Generator
// يقرأ كل ملفات .tsx / .ts ويولّد خريطة كاملة
// الهدف: أي AI جديد يعرف إيه موجود قبل ما يكتب كود جديد
// ═══════════════════════════════════════════════════════════
import { readdirSync, readFileSync, writeFileSync, statSync } from 'fs'
import { join, relative } from 'path'
import { fileURLToPath } from 'url'

const __dirname = fileURLToPath(new URL('.', import.meta.url))
const WEB = join(__dirname, '..')
const OUT = join(WEB, '..', 'docs', 'CONTEXT_MAP.md')

const IGNORE = ['node_modules', '.next', 'public', 'scripts', '.turbo']

function walk(dir, exts) {
  const out = []
  for (const entry of readdirSync(dir)) {
    if (IGNORE.includes(entry) || entry.startsWith('.')) continue
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) out.push(...walk(full, exts))
    else if (exts.some((e) => entry.endsWith(e))) out.push(full)
  }
  return out
}

function extract(file) {
  const src = readFileSync(file, 'utf-8')
  const exports = []
  const exportRe = /export\s+(?:default\s+)?(?:async\s+)?(?:function|const|class)\s+(\w+)/g
  let m
  while ((m = exportRe.exec(src)) !== null) exports.push(m[1])

  let desc = ''
  const lines = src.split('\n').slice(0, 40)
  for (const line of lines) {
    const t = line.trim()
    if (t.startsWith('//') && !t.startsWith('//!') && t.length > 5 && !t.includes('═')) {
      desc = t.replace(/^\/\/\s*/, '')
      break
    }
    if (t.startsWith('/**') || t.startsWith('/*')) {
      const block = src.match(/\/\*\*([\s\S]*?)\*\//)?.[1] ?? ''
      const first = block
        .split('\n')
        .map((l) => l.replace(/^\s*\*\s?/, '').trim())
        .find((l) => l && !l.startsWith('@') && !l.includes('═'))
      if (first) desc = first
      break
    }
  }
  return { exports, desc }
}

function fileToRoute(rel) {
  let r = rel.replace(/\\/g, '/').replace(/^app\//, '/')
  r = r.replace(/\/(page|layout|loading|error|not-found|route|template)\.tsx?$/, '')
  r = r.replace(/\([^)]+\)\//g, '')
  r = r.replace(/\/page$/, '')
  return r || '/'
}

function build() {
  const lines = []
  const now = new Date().toISOString().slice(0, 10)

  lines.push('# EAH — CONTEXT_MAP')
  lines.push('')
  lines.push('> ⚠️ **Auto-generated file** — لا تعدّل يدوياً.')
  lines.push('> Generated by: `npm run context-map`')
  lines.push(`> Last update: ${now}`)
  lines.push('')
  lines.push('> **الغرض:** أي AI أو مطور يقرأ ده **قبل** أي كود جديد.')
  lines.push('> يمنع التكرار + يوضح إيه موجود بالفعل.')
  lines.push('')
  lines.push('---')
  lines.push('')

  // ═══ Routes ═══
  const pages = walk(join(WEB, 'app'), ['.tsx', '.ts']).filter((f) =>
    /\/(page|route)\.tsx?$/.test(f),
  )
  const routes = pages
    .map((f) => ({ route: fileToRoute(relative(WEB, f)), file: relative(WEB, f) }))
    .sort((a, b) => a.route.localeCompare(b.route))

  lines.push(`## Routes (${routes.length})`)
  lines.push('')
  lines.push('| Route | File |')
  lines.push('|-------|------|')
  for (const r of routes) lines.push(`| \`${r.route}\` | \`${r.file}\` |`)
  lines.push('')

  // ═══ Components ═══
  const comps = walk(join(WEB, 'components'), ['.tsx']).filter(
    (f) => !f.endsWith('.module.css') && !f.includes('/icons/'),
  )
  const compInfo = comps
    .map((f) => {
      const rel = relative(WEB, f)
      const name = rel.replace(/^components\//, '')
      const { exports, desc } = extract(f)
      return { name, exports, desc }
    })
    .sort((a, b) => a.name.localeCompare(b.name))

  lines.push(`## Components (${compInfo.length})`)
  lines.push('')
  lines.push('| File | Export | Purpose |')
  lines.push('|------|--------|---------|')
  for (const c of compInfo) {
    const ex = c.exports.join(', ') || '—'
    const d = c.desc || '—'
    lines.push(`| \`${c.name}\` | ${ex} | ${d} |`)
  }
  lines.push('')

  // ═══ Lib ═══
  const libs = walk(join(WEB, 'lib'), ['.ts']).filter(
    (f) => !f.endsWith('.test.ts') && !f.endsWith('.d.ts'),
  )
  const libInfo = libs
    .map((f) => {
      const rel = relative(WEB, f)
      const name = rel.replace(/^lib\//, '')
      const { exports, desc } = extract(f)
      return { name, exports, desc }
    })
    .sort((a, b) => a.name.localeCompare(b.name))

  lines.push(`## Lib (${libInfo.length})`)
  lines.push('')
  lines.push('| File | Exports | Purpose |')
  lines.push('|------|---------|---------|')
  for (const l of libInfo) {
    const ex = l.exports.slice(0, 5).join(', ') + (l.exports.length > 5 ? ', …' : '') || '—'
    const d = l.desc || '—'
    lines.push(`| \`${l.name}\` | ${ex} | ${d} |`)
  }
  lines.push('')

  lines.push('---')
  lines.push('')
  lines.push('## القاعدة')
  lines.push('')
  lines.push('**قبل إنشاء أي ملف جديد:**')
  lines.push('')
  lines.push('1. ابحث في الخريطة دي')
  lines.push('2. لو موجود → استخدمه')
  lines.push('3. لو مش موجود → تأكد بـ `grep -rn "اسم" components/ lib/`')
  lines.push('4. بعدها بس → اكتب كود جديد')
  lines.push('')
  lines.push('المرجع: `AI_CONTRACT.md §18.1` (Zero Duplication) + `§19` (Pre-Edit Protocol)')
  lines.push('')

  writeFileSync(OUT, lines.join('\n'), 'utf-8')
  console.log(`✓ CONTEXT_MAP.md written: ${routes.length} routes, ${compInfo.length} components, ${libInfo.length} lib files`)
}

build()
